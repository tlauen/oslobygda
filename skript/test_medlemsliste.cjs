test('Årssatsar bruker eitt vanleg skjema; avslutting krev stadfesting og CSRF', async () => {
  const source = fs.readFileSync(path.join(root, 'medlemsregister/malar/kontingent.html'), 'utf8')
    .replace(/{%[\s\S]*?%}|{{[\s\S]*?}}/g, '');
  const dom = new JSDOM(source, {url: 'https://example.test/kontingent', runScripts: 'outside-only'});
  const {window: w} = dom;
  const d = w.document;
  d.querySelector('meta[name="csrf-token"]').content = 'test-csrf';
  const calls = [];
  let year = 2026;
  w.fetch = async (url, options) => {
    calls.push([url, options]);
    if (options.method === 'POST') year = 2027;
    return {ok: true, json: async () => ({medlemsbetalingsar: year, message: 'Medlemsåret er avslutta.'})};
  };
  w.eval(fs.readFileSync(path.join(root, 'medlemsregister/fast/kontingent-innstillingar.js'), 'utf8'));
  await tick();
  await tick();
  const close = d.getElementById('btn-lukk-medlemsar');
  assert.equal(close.disabled, false);
  d.getElementById('kontingent-innstillingar').dispatchEvent(new w.Event('submit', {cancelable: true}));
  assert.equal(calls.filter(([, options]) => options.method).length, 0);
  w.confirm = () => false;
  close.click();
  await tick();
  assert.equal(calls.filter(([, options]) => options.method).length, 0);
  w.confirm = () => true;
  w.prompt = () => '2026';
  close.click();
  await tick();
  await tick();
  const write = calls.find(([, options]) => options.method === 'POST');
  assert.equal(write[1].headers['X-CSRF-Token'], 'test-csrf');
  assert.deepEqual(JSON.parse(write[1].body), {bekreft_ar: 2026});
  assert.match(close.textContent, /2027/);
  assert.equal(close.disabled, false);
  w.prompt = () => '2027';
  w.fetch = async () => ({ok: false, json: async () => ({error: 'Året kunne ikkje avsluttast'})});
  close.click();
  await tick();
  assert.match(d.getElementById('kontingent-status').textContent, /kunne ikkje avsluttast/);
  assert.equal(close.disabled, false);
  w.close();
});

test('Namnet opnar detaljar; den namngjevne handlingsmenyen verkar også frå ikonet', async () => {
  const {w, d, calls} = await start([members[0]]);
  assert.equal(d.querySelectorAll('[data-action="detail"]').length, 1);
  assert.equal(d.querySelector('th[data-col="fødselsdato"]').textContent, 'Fødd');
  assert.equal(d.querySelector('.aksjonar-meny-prikker'), null);
  const button = d.querySelector('.aksjonar-meny-knapp');
  const menu = d.getElementById(button.getAttribute('aria-controls'));
  assert.match(button.textContent, /Handlingar/);
  button.getBoundingClientRect = () => ({top: 700, bottom: 744, right: 980});
  menu.getBoundingClientRect = () => ({width: 180, height: 188});
  button.querySelector('path').dispatchEvent(new w.MouseEvent('click', {bubbles: true}));
  assert.equal(menu.hidden, false);
  assert.equal(button.getAttribute('aria-expanded'), 'true');
  assert.ok(parseFloat(menu.style.top) + 188 < 700, 'Menyen må få plass over knappen nær botnen');
  assert.ok(parseFloat(menu.style.left) >= 8);
  assert.ok(parseFloat(menu.style.left) + 180 <= w.innerWidth - 8);
  d.dispatchEvent(new w.KeyboardEvent('keydown', {key: 'Escape', bubbles: true}));
  assert.equal(menu.hidden, true);
  assert.equal(d.activeElement, button);
  button.querySelector('span').click();
  assert.equal(menu.hidden, false);
  d.body.click();
  assert.equal(menu.hidden, true);
  d.querySelector('.medlem-lenkje').click();
  assert.equal(d.getElementById('medlem-detalj').open, true);
  d.getElementById('medlem-detalj-lukk').click();
  button.click();
  menu.querySelector('[data-action="edit"]').click();
  await tick();
  assert.equal(d.getElementById('modal-dekke').getAttribute('aria-hidden'), 'false');
  assert.equal(d.getElementById('modal-dekke').style.display, 'flex');
  assert.equal(d.getElementById('medlem-id').value, '1');
  assert.equal(calls.some(([, options]) => ['POST', 'PUT', 'DELETE'].includes(options.method)), false);
  w.close();
});
